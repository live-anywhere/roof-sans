import pytest

from roofsans import web

SLICING = """# Generated by a tool; DO NOT MODIFY BY HAND
# Note that subsets are listed in reverse order to match unicode-range prioritization
subsets {
  codepoints: 12354 # あ HIRAGANA LETTER A
  codepoints: 12356 # い HIRAGANA LETTER I
}
subsets {
  codepoints: 19968 # 一 CJK UNIFIED IDEOGRAPH-4E00
}
"""


def test_parse_slicing_reads_subsets_in_file_order():
    assert web.parse_slicing(SLICING) == [[0x3042, 0x3044], [0x4E00]]


@pytest.mark.parametrize("text", ["subsets {\n  codepoints: x\n}\n", "codepoints: 1\n", "subsets {\n  codepoints: 1\n"])
def test_parse_slicing_rejects_unexpected_input(text):
    with pytest.raises(ValueError):
        web.parse_slicing(text)


def test_unicode_range_merges_runs_and_round_trips():
    cps = {0x20, 0x21, 0x22, 0x41, 0xAC00, 0xAC01, 0x20000}
    value = web.unicode_range(cps)
    assert value == "U+20-22, U+41, U+ac00-ac01, U+20000"
    assert web.parse_unicode_range(value) == cps


def test_plan_chunks_fixed_groups_then_slicings_then_leftovers(monkeypatch):
    monkeypatch.setattr(web, "MIN_CHUNK", 1)
    monkeypatch.setattr(web, "LEFTOVER_SIZE", 2)
    cps = {0x41, 0x2019, 0x0301, 0x0100, 0x2192, 0x3042, 0x4E00, 0x4E01, 0xAC00, 0x5000, 0x5001, 0x5002}
    slicings = [
        ("ja", [[0x3042], [0x4E00, 0x9999]]),
        ("ko", [[0xAC00, 0x4E00]]),  # 4E00 is already Japanese
        ("zhs", [[0x4E01]]),
    ]
    chunks = web.plan_chunks(cps, slicings)
    assert [(c.source, c.codepoints) for c in chunks] == [
        ("latin", (0x41, 0x0301, 0x2019)),
        ("latin-ext", (0x0100,)),
        ("symbols-2100", (0x2192,)),
        ("ja 0", (0x3042,)),
        ("ja 1", (0x4E00,)),
        ("ko 0", (0xAC00,)),
        ("zhs 0", (0x4E01,)),
        ("leftover 0", (0x5000, 0x5001)),
        ("leftover 1", (0x5002,)),
    ]


def test_plan_chunks_merges_remnants_of_one_slicing(monkeypatch):
    monkeypatch.setattr(web, "MIN_CHUNK", 3)
    cps = {0xAC00, 0xAC01, 0xAC02, 0xAC03, 0x4E00}
    slicings = [
        ("ja", [[0x4E00]]),
        ("ko", [[0xAC00, 0x4E00], [0xAC01], [0xAC02, 0xAC03], [0x4E00]]),
    ]
    chunks = web.plan_chunks(cps, slicings)
    assert [(c.source, c.codepoints) for c in chunks] == [
        ("ja 0", (0x4E00,)),
        ("ko 0-2", (0xAC00, 0xAC01, 0xAC02, 0xAC03)),
    ]


def test_plan_chunks_is_a_partition():
    cps = set(range(0x20, 0x3000)) | set(range(0xAC00, 0xAD00))
    chunks = web.plan_chunks(cps, [("ko", [list(range(0xAC00, 0xAC80))])])
    seen = [cp for c in chunks for cp in c.codepoints]
    assert len(seen) == len(set(seen)) and set(seen) == cps


def test_font_face_lists_unicode_range_only_for_subsets():
    full = web.font_face("./woff2/RoofSansVariable.woff2", "400 1000")
    part = web.font_face("./x.woff2", "400 1000", [0x41, 0x42])
    assert "unicode-range" not in full
    assert "font-family: 'Roof Sans';" in full and "font-weight: 400 1000;" in full
    assert "src: url('./x.woff2') format('woff2');" in part
    assert "unicode-range: U+41-42;" in part


def test_subset_request_adds_the_selectors_of_its_bases():
    chunk = web.Chunk("ja 0", (0x559D, 0x3042))
    selectors = {0x559D: {0xFE00, 0xE0100}, 0x6F22: {0xE0101}}
    assert web.subset_request(chunk, selectors) == (0x3042, 0x559D, 0xFE00, 0xE0100)
    assert web.subset_request(web.Chunk("latin", (0x41,)), selectors) == (0x41,)
